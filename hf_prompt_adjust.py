OPENAI_API_KEY = ""

# Expanded contract smells definitions
SMELL_DESCRIPTIONS = """
LazyClass: Code that lacks specificity or detail, or is ambiguous, or clause that adds no real legal weight as it is not detailed enough to be enforceable or effective, will only make the contract longer, more complex to understand.
InappropIntimacy: In code, classes coupled too tightly run risks. Contracts often include dependencies between clauses or sentences that are tightly dependent within a clause.
"""

# ---------------------------------------
# Load Clause Data
