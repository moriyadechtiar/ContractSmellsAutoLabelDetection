DRIVE_PATH_LAZY = "/content/drive/My Drive/MyModels/legal-bert-base-coding/autol_incorrect_predictions_lazyclass.csv"
DRIVE_PATH_INAPROP = "/content/drive/My Drive/MyModels/legal-bert-base-coding/autol_incorrect_predictions_InappropIntimacy.csv"
OUTPUT_PATH_LAZY = "/content/drive/My Drive/MyModels/legal-bert-base-coding/autol_fewshot_predictions_lazyclass.csv"
