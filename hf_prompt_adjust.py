print("Loading clause data...")
preds_lazy = pd.read_csv(DRIVE_PATH_LAZY)
preds_inaprop = pd.read_csv(DRIVE_PATH_INAPROP)

print("LazyClass Data Sample:")
print(preds_lazy.head())

