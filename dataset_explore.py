def is_str(example):
    """
    Checks if 'ClauseText' in the example is a string.
    """
    return isinstance(example['ClauseText'], str)

def keep_valid_rows(example, labels):
    """
    Validates that each class column is either '0' or '1' (after converting from string/float if needed).
    Returns True if valid, False otherwise.
    """
    try:
        for column in labels:
            if example[column] is None:
                return False
            value_as_int = int(float(example[column]))
            if value_as_int not in [0, 1]:
                return False
        return True
    except (ValueError, TypeError):
        # If conversion fails or data is malformed, discard the row
        return False

def convert_labels(example, labels):
    """
    Converts class label columns from string/float to integers.
    """
    for category in labels:
        example[category] = int(float(example[category]))
    return example


def plot_class_distribution(df: pd.DataFrame, title: str, labels):
    """
    Plots the distribution of class counts for a given DataFrame.
    """
    class_distribution = df[labels].sum().sort_values(ascending=False)
    plt.figure(figsize=(10, 6))
    class_distribution.plot(kind='bar')
    plt.title(f'Distribution of Classes - {title}')
    plt.xlabel('Classes')
    plt.ylabel('Number of Instances')
    plt.xticks(rotation=45)
    plt.show()

def plot_correlation_heatmap(df: pd.DataFrame, title: str, labels):
    """
    Plots a correlation matrix heatmap for the class label columns in df.
    """
    class_df = df[labels]
    correlation_matrix = class_df.corr()
    
    plt.figure(figsize=(10, 8))
    sns.heatmap(correlation_matrix, annot=True, cmap='coolwarm', fmt=".2f", linewidths=.5)
    plt.title(f'Correlation Matrix of Classes - {title}')
    plt.show()

def print_class_percentages(df: pd.DataFrame, title: str, labels):
    """
    Prints the percentage of instances for each class for a given DataFrame.
    """
    class_counts = df[labels].sum()
    total_instances = len(df)
    class_percentages = (class_counts / total_instances) * 100
    
    print(f"Percentage of instances for each class - {title}:")
    print(class_percentages)
    print()


def print_class_imbalance_info(df, title, labels):
    class_counts = df[labels].sum()
    total = len(df)
    print(f"\nClass Imbalance Info - {title}:")
    for cls in labels:
        pos = class_counts[cls]
        neg = total - pos
        pos_ratio = pos / total
        neg_ratio = neg / total
        print(f"{cls}: {pos} positives, {neg} negatives (Pos ratio: {pos_ratio:.2f}, Neg ratio: {neg_ratio:.2f})")

def co_occurrence_matrix(df, labels):
    matrix = pd.DataFrame(0, index=labels, columns=labels)
    for cls1 in labels:
        for cls2 in labels:
            # Count rows where both cls1 and cls2 are 1
            count = len(df[(df[cls1] == 1) & (df[cls2] == 1)])
            matrix.loc[cls1, cls2] = count
    return matrix

def get_top_words(df, class_label, class_value=1, top_n=20):
    subset = df[df[class_label] == class_value]['ClauseText'].dropna().values
    words = []
    for clause in subset:
        words.extend(str(clause).lower().split())
    counter = Counter(words)
    return counter.most_common(top_n)


