def get_embeddings(texts, tokenizer, model, batch_size=32):
    """
    Obtain embeddings for a list of texts using a transformer model.
    We'll use the [CLS] token embeddings as a basic representation.
    """
    model.eval()
    embeddings = []
    with torch.no_grad():
        for i in range(0, len(texts), batch_size):
            batch_texts = texts[i:i+batch_size]
            inputs = tokenizer(batch_texts, return_tensors='pt', padding=True, truncation=True, max_length=128)
            outputs = model(**inputs)
            # CLS token embedding is at index 0
            cls_embeddings = outputs.last_hidden_state[:, 0, :]
            embeddings.append(cls_embeddings.cpu())
    return torch.cat(embeddings, dim=0).numpy()

def run_pca_plot(
    df: pd.DataFrame,
    tokenizer,
    model,
    label_col: str = 'DuplicateCode',
    sample_size: int = 500,
    random_state: int = 42,
    title: str = 'PCA of Clause Embeddings'
):
    """
    Runs PCA on a subset of the given DataFrame (df), projects embeddings to 2D, and plots them colored by the specified label_col.

    Args:
        df (pd.DataFrame): DataFrame containing a 'ClauseText' column and a binary label column.
        tokenizer: A tokenizer compatible with the chosen model.
        model: A transformer model used to generate embeddings.
        label_col (str): The column in df to use for coloring points. Must be binary (0/1).
        sample_size (int): Number of clauses to sample for PCA visualization.
        random_state (int): Random seed for sampling reproducibility.
        title (str): Title for the plot.
    """
    # Sample the DataFrame
    sample_size = min(sample_size, len(df))
    sample_df = df.sample(sample_size, random_state=random_state)
    sample_texts = sample_df['ClauseText'].tolist()

    # Obtain embeddings for the sampled clauses
    clause_embeddings = get_embeddings(sample_texts, tokenizer, model)  # Assuming get_embeddings is defined

    # Apply PCA to reduce dimensionality
    pca = PCA(n_components=2)
    reduced_embeddings = pca.fit_transform(clause_embeddings)

    # Extract labels for visualization
    labels = sample_df[label_col].values
    plt.figure(figsize=(10, 8))
    plt.scatter(reduced_embeddings[labels==0, 0], reduced_embeddings[labels==0, 1], alpha=0.7, label=f'{label_col}=0')
    plt.scatter(reduced_embeddings[labels==1, 0], reduced_embeddings[labels==1, 1], alpha=0.7, label=f'{label_col}=1')

    plt.title(title)
    plt.xlabel('PC1')
    plt.ylabel('PC2')
    plt.legend()
    plt.show()


