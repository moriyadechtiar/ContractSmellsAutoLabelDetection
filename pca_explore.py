def is_str(example):
    """
    Checks if 'ClauseText' in the example is a string.
    """
    return isinstance(example['ClauseText'], str)

def keep_valid_rows(example, labels):
    """
    Validates that each class column is either '0' or '1' (after converting from string/float if needed).
    Returns True if valid, False otherwise.
    """
    try:
        for column in labels:
            if example[column] is None:
                return False
            value_as_int = int(float(example[column]))
            if value_as_int not in [0, 1]:
                return False
        return True
    except (ValueError, TypeError):
        # If conversion fails or data is malformed, discard the row
        return False

def convert_labels(example, labels):
    """
    Converts class label columns from string/float to integers.
    """
    for category in labels:
        example[category] = int(float(example[category]))
    return example


